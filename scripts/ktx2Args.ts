// The exact ktx arguments of the KTX2 encode stages, as a pure builder.
//
// The encode plan (ktx2Plan.ts) reproduces what gltf-transform 4.5.1's
// texture commands do per texture, read from the CLI source (dist/cli.mjs):
// the toktx function spawns one `ktx create` per texture with the
// parameters of createParams (cli.mjs 699-745), and resizes the image
// beforehand to fit the stage's maximum, rounded up to a multiple of four
// (cli.mjs 650-666). Two things are deliberate differences, both required
// by byte determinism:
//
// - `--threads 1` always: the CLI passes Math.max(2, ...) (cli.mjs
//   740-743) when more than one texture is in the document, and
//   KTX-Software 4.4.2's UASTC encode with RDO is only byte-stable
//   single-threaded. A single-texture document gets no --threads at all
//   from the CLI, which is threaded by default, so the flag is passed for
//   every texture, not only for multi-texture documents.
// - `--width` and `--height` instead of the CLI's sharp resize: the
//   resampling moves into the encoder, which resamples to the same
//   dimensions by the same fit rule; sharp itself is not a declared
//   dependency. The project resize rule is the encoder's native
//   linear-light averaging: it is physically correct, and it is the same
//   rule the encoder applies when it builds the mip chain, so base levels
//   and mips shrink by one rule. Color textures are authored at or under
//   textureMaxSize, so a resized sRGB texture is the exception, and
//   linear-light averaging is what it gets. The mipmap filter stays at
//   KTX-Software's default (lanczos4), which is also what the CLI's
//   mipmap generation uses, since neither the CLI nor this builder passes
//   --mipmap-filter.
//
// The flags the CLI writes only for non-default encoder options are written
// unconditionally here: the settings fix those values to the CLI's optimize
// defaults, which all differ from the standalone commands' defaults, so the
// emitted arguments are the same set the CLI emits (see settings.ts).
import { TextureChannel } from '@gltf-transform/core'
import { fitWithin } from '@gltf-transform/functions'
import type { OptimizeSettings } from './settings.ts'

// The two bitstream modes, named as the CLI names them (Mode in cli.mjs).
export type Ktx2Mode = 'uastc' | 'etc1s'

// The texture color space as getTextureColorSpace reports it: sRGB or
// linear (null).
export type TextureColorSpace = 'srgb' | null

// UASTC RDO post-processing distorts normal maps, so the CLI skips it for
// any texture used in a slot whose name contains 'normal' (cli.mjs 705,
// the glob '*normal*' with case-insensitive substring semantics).
export function isNormalMapSlot(slots: readonly string[]): boolean {
  return slots.some((slot) => slot.toLowerCase().includes('normal'))
}

// The encoded size of a texture: scaled to fit the stage's maximum, then
// rounded up to a multiple of four because KTX2 needs block-aligned sizes
// (cli.mjs 655-657 and 756-762). Values at or below four clamp to four,
// the smallest block-aligned size.
export function encodedSize(srcSize: readonly [number, number], maxSize: number): [number, number] {
  const ceilMultipleOfFour = (value: number): number => (value <= 4 ? 4 : 4 * Math.ceil(value / 4))
  const [fittedWidth, fittedHeight] = fitWithin([...srcSize], [maxSize, maxSize])
  return [ceilMultipleOfFour(fittedWidth), ceilMultipleOfFour(fittedHeight)]
}

// The Vulkan format of the encoded texture, from the channels the slots
// read and the color space (cli.mjs 736-739).
export function encodedFormat(channels: number, colorSpace: TextureColorSpace): string {
  const { R, G, A } = TextureChannel
  if (channels === R) {
    return 'R8_UNORM'
  }
  if (channels === G || channels === (R | G)) {
    return 'R8G8_UNORM'
  }
  if ((channels & A) === 0) {
    return colorSpace === 'srgb' ? 'R8G8B8_SRGB' : 'R8G8B8_UNORM'
  }
  return colorSpace === 'srgb' ? 'R8G8B8A8_SRGB' : 'R8G8B8A8_UNORM'
}

export type Ktx2TextureFacts = {
  mode: Ktx2Mode
  slots: readonly string[]
  colorSpace: TextureColorSpace
  channels: number
  srcSize: readonly [number, number]
  maxSize: number
  settings: OptimizeSettings
}

// The full ktx create arguments for one texture: the parameters in the
// order of createParams (cli.mjs 699-745), then the input and output file
// names appended last, as the CLI's toktx appends them (cli.mjs 670-675).
export function buildKtxCreateArgs(
  facts: Ktx2TextureFacts,
  srcPath: string,
  dstPath: string,
): string[] {
  const { settings } = facts
  const params: string[] = []
  // Mipmaps are always generated by the encoder itself, the gltf-transform
  // optimize KTX2 default; the viewer's samplers expect them.
  params.push('--generate-mipmap')
  const normalMap = isNormalMapSlot(facts.slots)
  if (facts.mode === 'uastc') {
    params.push('--encode', 'uastc', '--uastc-quality', String(settings.uastcLevel))
    if (settings.uastcRdo && !normalMap) {
      params.push('--uastc-rdo', '--uastc-rdo-l', String(settings.uastcRdoLambda))
      if (!settings.uastcRdoMultithreading) {
        params.push('--uastc-rdo-m')
      }
    }
    params.push('--zstd', String(settings.uastcZstd))
  } else {
    // The CLI's ETC1S endpoint and selector RDO stay on with default
    // thresholds, which emit no flags (cli.mjs 724-730); a normal map
    // gets the explicit no-RDO flags instead (cli.mjs 731).
    params.push('--encode', 'basis-lz', '--qlevel', String(settings.etc1sQuality))
    if (normalMap) {
      params.push('--no-endpoint-rdo', '--no-selector-rdo')
    }
  }
  if (facts.colorSpace === 'srgb') {
    params.push('--assign-tf', 'srgb', '--assign-primaries', 'bt709')
  } else if (facts.slots.length > 0) {
    params.push('--assign-tf', 'linear', '--assign-primaries', 'none')
  }
  params.push('--format', encodedFormat(facts.channels, facts.colorSpace))
  const [dstWidth, dstHeight] = encodedSize(facts.srcSize, facts.maxSize)
  if (dstWidth !== facts.srcSize[0] || dstHeight !== facts.srcSize[1]) {
    params.push('--width', String(dstWidth), '--height', String(dstHeight))
  }
  params.push('--threads', String(settings.ktxThreads))
  return ['create', ...params, srcPath, dstPath]
}
